#!/usr/bin/env bash

# GDPR usage simulation of the front (MAIR-497, mairie360/CICD tests/gdpr/simulation). Test stack
# only: needs GDPR_SIMULATION=test-stack (the CICD action exports it), the engine refuses anything
# else.
#
#   1. docker-compose-gdpr-simulation.yml: the `gdpr-simulation` runner plays gdpr-journey.yaml for
#      fictitious personas through the front's own origin, opens the pages of the `browser` section
#      of gdpr-simulation.yaml for each of them in Chromium (console, storage, requests, cookies),
#      then the `erase` steps, and writes gdpr-simulation/;
#   2. the rows of the run are back-dated past their retention, then the purge runs
#      (fn_apply_retention_policies);
#   3. the database checks generated by the engine from the inventory (Devops/Database
#      gdpr/inventory.yaml at GDPR_INVENTORY_REF, `main` by default) and the schema are run;
#   4. the Redis keys with their TTL and the logs of every container are saved, then the stack is
#      removed.
# The CICD action then runs analyze.mjs on gdpr-simulation/ (deterministic checks + AI review).
# Exit 0: everything played; 1: a step failed; 2: missing input.
#
# The front under test is IMAGE_REF (CI: the image promoted to staging); empty, it is built from the
# Dockerfile as login-front:local (NODE_AUTH_TOKEN needed for the @mairie360 packages), or point
# IMAGE_REF at a published image, e.g. IMAGE_REF=ghcr.io/mairie360/login-front:dev.

COMPOSE_FILE="docker-compose-gdpr-simulation.yml"
RUN_DIR="gdpr-simulation"
DB="mairie_360_database"
INVENTORY_REF="${GDPR_INVENTORY_REF:-main}"

if [ "${GDPR_SIMULATION:-}" != "test-stack" ]; then
    echo "GDPR_SIMULATION=test-stack is not set: the simulation only runs on a test stack."
    exit 2
fi
export GDPR_SIMULATION

if [ -z "${IMAGE_REF:-}" ]; then
    echo "==> [0/5] Building login-front:local from the Dockerfile..."
    docker build -t login-front:local --secret id=node_auth_token,env=NODE_AUTH_TOKEN . || exit 1
    export IMAGE_REF="login-front:local"
fi
echo "==> Front under test: $IMAGE_REF"

# Session of the run: an HS256 JWT {sub, role, exp} for the seeded user 1, signed with the
# stack's JWT_SECRET (docker-compose-gdpr-simulation.yml), like the RGAA engine's sessions.
JWT_SECRET='b"secret"'
b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }
jwt_header="$(printf '{"alg":"HS256","typ":"JWT"}' | b64url)"
jwt_payload="$(printf '{"sub":"1","role":"admin","exp":%s}' "$(( $(date +%s) + 3600 ))" | b64url)"
jwt_signature="$(printf '%s.%s' "$jwt_header" "$jwt_payload" | openssl dgst -sha256 -hmac "$JWT_SECRET" -binary | b64url)"
[ -n "$jwt_signature" ] || { echo "Could not sign the session of the run (openssl)."; exit 1; }
export ADMIN_JWT="$jwt_header.$jwt_payload.$jwt_signature"

# Engine at the cicd_version pinned in .github/workflows/cicd.yml (override with CICD_VERSION), fetched
# like accessibility_test.sh does (a SHA, a tag or a branch; .rgaa-ref records the ref of a copy
# fetched here). The simulation of the fronts needs tests/gdpr/simulation/browse.mjs: until the pin
# names a CICD release that has it, set CICD_VERSION. Without .rgaa-ref, a cicd-repo/ is used as is
# only in GitHub Actions (the CI checks the engine out itself); locally the script stops instead of
# deleting it, since it may be a clone holding local work.
CICD_DIR="cicd-repo"
CICD_VERSION="${CICD_VERSION:-$(sed -n 's/^[[:space:]]*cicd_version:[[:space:]]*"\{0,1\}\([^"[:space:]#]*\).*/\1/p' .github/workflows/cicd.yml | head -n 1)}"
engine_complete() {
    for f in simulation/simulate.mjs simulation/browse.mjs simulation/sql.mjs privacy/privacy.mjs privacy/runner-image schema.sql package-lock.json; do
        [ -f "$CICD_DIR/tests/gdpr/$f" ] || return 1
    done
}
if [ -d "$CICD_DIR" ] && [ ! -f "$CICD_DIR/.rgaa-ref" ] && [ "${GITHUB_ACTIONS:-}" != "true" ]; then
    echo "$CICD_DIR/ was not fetched by this script (no .rgaa-ref) and may hold local work: move or delete it, then run again." >&2
    exit 1
fi
if ! engine_complete ||
    { [ -f "$CICD_DIR/.rgaa-ref" ] && [ "$(cat "$CICD_DIR/.rgaa-ref")" != "$CICD_VERSION" ]; }; then
    if [ -z "$CICD_VERSION" ]; then
        echo "No cicd_version found in .github/workflows/cicd.yml (set CICD_VERSION)." >&2
        exit 1
    fi
    echo "==> Fetching mairie360/CICD $CICD_VERSION into $CICD_DIR/..."
    rm -rf "$CICD_DIR"
    git init --quiet "$CICD_DIR" &&
        git -C "$CICD_DIR" fetch --quiet --depth 1 https://github.com/mairie360/CICD "$CICD_VERSION" &&
        git -C "$CICD_DIR" -c advice.detachedHead=false checkout --quiet FETCH_HEAD || exit 1
    printf '%s\n' "$CICD_VERSION" > "$CICD_DIR/.rgaa-ref"
    engine_complete || { echo "mairie360/CICD $CICD_VERSION has no GDPR simulation for the fronts (tests/gdpr/simulation/browse.mjs): set CICD_VERSION."; exit 1; }
fi
GDPR_RUNNER_IMAGE="$(cat "$CICD_DIR/tests/gdpr/privacy/runner-image")"
export GDPR_RUNNER_IMAGE
export GDPR_UID="${GDPR_UID:-$(id -u)}" GDPR_GID="${GDPR_GID:-$(id -g)}"

rm -rf "$RUN_DIR" && mkdir -p "$RUN_DIR/db" "$RUN_DIR/redis"
curl -fsSL "https://raw.githubusercontent.com/mairie360/Database/$INVENTORY_REF/gdpr/inventory.yaml" -o "$RUN_DIR/inventory.yaml" \
    || { echo "No gdpr/inventory.yaml at mairie360/Database@$INVENTORY_REF (GDPR_INVENTORY_REF)."; exit 2; }

# The stack is always removed, even when the script is interrupted (CI bounds it with `timeout`).
# The logs are saved first when the run stops before step 4, so a failure can still be read.
cleanup() {
    [ -s "$RUN_DIR/containers.log" ] || docker compose -f "$COMPOSE_FILE" logs --no-color > "$RUN_DIR/containers.log" 2>/dev/null
    docker compose -f "$COMPOSE_FILE" down -v >/dev/null 2>&1
}
trap cleanup EXIT
psql_stack() {
    docker compose -f "$COMPOSE_FILE" exec -T postgres psql -U postgres -d "$DB" -v ON_ERROR_STOP=1 -At "$@"
}

echo "==> [1/5] Starting the stack, the personas' journeys and their pages..."
# Fresh volumes on every run: a volume left by a previous run would hand the stack its rows.
if ! docker compose -f "$COMPOSE_FILE" down -v --remove-orphans > /dev/null 2>&1; then
    echo "Could not remove the previous stack and its volumes: its rows would reach this run."
    exit 1
fi
# A failed dependency (seeder, migration, upstream readiness) leaves the runner created but never
# started, and `docker compose wait` would then report 0: fail here instead.
if ! docker compose -f "$COMPOSE_FILE" up -d --pull missing; then
    echo "==> The stack did not start: a dependency failed. Logs:"
    docker compose -f "$COMPOSE_FILE" logs --tail 80
    exit 1
fi
docker compose -f "$COMPOSE_FILE" wait gdpr-simulation
RUNNER_EXIT=$?
docker compose -f "$COMPOSE_FILE" logs --no-color --tail 60 gdpr-simulation

echo "==> [2/5] Back-dating the rows of the run past their retention, then the purge..."
# Sessions and connection logs are the tables a retention policy purges today; the rows the
# journey wrote elsewhere are checked as they are. The run's session is a signed JWT with no
# sessions row, so a probe session is written first: the purge must remove it once back-dated,
# otherwise the back-dating touched nothing and the retention check would pass on an empty table.
# ON_ERROR_STOP: a failed statement stops psql, and the run with it (the checks would read a
# database that was never purged).
psql_stack <<'SQL' || { echo "The back-dating or the purge failed."; exit 1; }
INSERT INTO sessions (user_id, token_hash, device_info, created_at, expires_at)
VALUES (1, 'gdpr-simulation-retention-probe', 'gdpr simulation', now(), now() + interval '1 hour');
UPDATE sessions SET created_at = created_at - interval '7 months', expires_at = expires_at - interval '7 months'
 WHERE created_at > now() - interval '1 day';
UPDATE connection_logs SET timestamp = timestamp - interval '13 months'
 WHERE timestamp > now() - interval '1 day';
SELECT * FROM fn_apply_retention_policies();
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM sessions WHERE token_hash = 'gdpr-simulation-retention-probe') THEN
        RAISE EXCEPTION 'the purge kept the back-dated probe session';
    END IF;
END
$$;
SQL

echo "==> [3/5] Database checks..."
psql_stack -f - < "$CICD_DIR/tests/gdpr/schema.sql" > "$RUN_DIR/schema.json" || exit 1
docker run --rm -u "$(id -u):$(id -g)" -e HOME=/tmp -v "$PWD/$CICD_DIR/tests/gdpr:/engine:ro" -v "$PWD/$RUN_DIR:/run" node:24-bookworm-slim sh -c \
    'mkdir -p /tmp/engine && tar -C /engine --exclude=./node_modules -cf - . | tar -C /tmp/engine -xf - && cd /tmp/engine && npm ci --omit=dev --no-audit --no-fund --loglevel=error && node simulation/sql.mjs /run/inventory.yaml /run/schema.json /run' \
    || exit 1
for query in erasure retention content; do
    psql_stack -f - < "$RUN_DIR/db/$query.sql" > "$RUN_DIR/db/$query.sql.json" || exit 1
done

echo "==> [4/5] Saving the Redis keys and the logs of every container..."
# Key and TTL of every Redis key (MAIR-499: a key without TTL or outside the inventory's prefixes fails).
# A failed scan or TTL read stops the run: an empty or partial keys.tsv would pass as clean.
docker compose -f "$COMPOSE_FILE" exec -T redis sh -c \
    'set -e; keys="$(redis-cli --scan)"; for k in $keys; do ttl="$(redis-cli TTL "$k")"; [ -n "$ttl" ]; printf "%s\t%s\n" "$k" "$ttl"; done' \
    > "$RUN_DIR/redis/keys.tsv" || { echo "Could not read the Redis keys: the analysis would not be reliable."; exit 1; }
# The services are stopped first, so that the file holds every line they wrote. Missing or
# truncated logs would let the analysis pass as clean: stop instead.
docker compose -f "$COMPOSE_FILE" stop >/dev/null 2>&1 || { echo "Could not stop the stack before saving its logs."; exit 1; }
if ! docker compose -f "$COMPOSE_FILE" logs --no-color > "$RUN_DIR/containers.log" \
    || [ ! -s "$RUN_DIR/containers.log" ]; then
    echo "Could not save the container logs: the analysis would not be reliable."
    exit 1
fi

# The session of the run is a credential: its signature must not appear in any log.
if grep -qF -- "${ADMIN_JWT##*.}" "$RUN_DIR/containers.log"; then
    echo "The session JWT of the run appears in the container logs."
    exit 1
fi

echo "==> [5/5] Removing the stack..."
docker compose -f "$COMPOSE_FILE" down -v

echo "Runner exit code: $RUNNER_EXIT"
[ "$RUNNER_EXIT" -eq 0 ] || exit 1
exit 0
